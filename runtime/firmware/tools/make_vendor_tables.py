"""Generate the text and clock tables the stock firmware uses, from its image.

    py runtime/firmware/tools/make_vendor_tables.py [vendor-app.bin]

Reads the vendor application 0ab195d6... (default: analysis/vendor-0ab195d6-app1.bin)
and writes:

  components/fw_text/vendor_charmap.c   Unicode -> font glyph map (134 entries) and
                                        the 63 extra 5x8 glyphs stock text falls back to
  components/fw_clock/clock_tables.c    the clock's 42 date glyphs, 19 locales of
                                        weekday/month names, 20 zone abbreviations

Every table is located through the literal words the vendor code loads (see
CLOCK.md for the functions), and the image hash is checked first, so the
output can only come from that exact build.
"""
import hashlib
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW = HERE.parent
DEFAULT_IMAGE = FW.parents[1] / 'analysis' / 'vendor-0ab195d6-app1.bin'
IMAGE_SHA256 = '0ab195d6b9ea5206b90a50339b9c61ece38da36f48900d8482e855e8f890559f'
CHARMAP_OUT = FW / 'components' / 'fw_text' / 'vendor_charmap.c'
CLOCK_OUT = FW / 'components' / 'fw_clock' / 'clock_tables.c'

# Literal words in the vendor code (IROM) that hold each table's address.
LIT_CHARMAP = (0x42000dec, 0x42000df0)   # FUN_4201bae8: {u16 code point, u16 glyph}
LIT_EXTRA = (0x42000de4, 0x42000de8)     # FUN_4201baac: {u32 code point, u8 rows[8]}
LIT_DATE_GLYPHS = (0x420007f8, 0x420007fc)  # FUN_4200f7ec: {u32 code point, u8 rows[8]}
LIT_LOCALES = 0x420003f0                 # FUN_42007664: 19 x {code, 7 weekdays, 12 months}
LIT_ZONE_NAMES = 0x42000ca8              # FUN_42019f90: 20 x {i16 minutes, pad, name}
LOCALES, ZONES = 19, 20


class Image:
    def __init__(self, data):
        if data[0] != 0xE9:
            sys.exit('not an ESP application image')
        self.segs, off = [], 24
        for _ in range(data[1]):
            addr, n = struct.unpack_from('<II', data, off)
            self.segs.append((addr, data[off + 8:off + 8 + n]))
            off += 8 + n

    def read(self, addr, n):
        for base, blob in self.segs:
            if base <= addr and addr + n <= base + len(blob):
                return blob[addr - base:addr - base + n]
        raise KeyError(hex(addr))

    def u32(self, addr):
        return struct.unpack('<I', self.read(addr, 4))[0]

    def cstr(self, addr):
        out = bytearray()
        while True:
            b = self.read(addr + len(out), 1)[0]
            if b == 0:
                return bytes(out).decode('utf-8')
            out.append(b)


def c_string(s):
    out = ''
    for b in s.encode('utf-8'):
        out += chr(b) if 0x20 <= b < 0x7F and chr(b) not in '"\\' else '\\x%02X' % b
    # A hex escape swallows following hex digits; split the literal after one.
    parts, cur = [], ''
    i = 0
    while i < len(out):
        if out.startswith('\\x', i):
            cur += out[i:i + 4]
            i += 4
            if i < len(out) and not out.startswith('\\x', i) and out[i] in '0123456789abcdefABCDEF':
                parts.append(cur)
                cur = ''
        else:
            cur += out[i]
            i += 1
    parts.append(cur)
    return ' '.join('"%s"' % p for p in parts)


def glyph_rows(img, lits):
    begin, end = img.u32(lits[0]), img.u32(lits[1])
    if (end - begin) % 12:
        sys.exit('glyph table size is not a multiple of 12')
    out = []
    for a in range(begin, end, 12):
        cp = img.u32(a)
        rows = img.read(a + 4, 8)
        if any(r & 0xE0 for r in rows):
            sys.exit('glyph U+%04X uses more than 5 columns' % cp)
        out.append((cp, rows))
    if [cp for cp, _ in out] != sorted(cp for cp, _ in out):
        sys.exit('glyph table is not sorted (the vendor binary-searches it)')
    return out


def glyph_lines(glyphs):
    return '\n'.join('    {0x%04X, {%s}},  /* %s */' % (cp, ', '.join('0x%02X' % r for r in rows), chr(cp))
                     for cp, rows in glyphs)


HEADER = ('/* GENERATED by tools/make_vendor_tables.py from the vendor application\n'
          ' * %s - do not edit. */\n' % IMAGE_SHA256)


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_IMAGE
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != IMAGE_SHA256:
        sys.exit('%s is not vendor application %s' % (path, IMAGE_SHA256[:8]))
    img = Image(data)

    begin, end = img.u32(LIT_CHARMAP[0]), img.u32(LIT_CHARMAP[1])
    charmap = [struct.unpack('<HH', img.read(a, 4)) for a in range(begin, end, 4)]
    if len(charmap) != 134 or [c for c, _ in charmap] != sorted(c for c, _ in charmap):
        sys.exit('unexpected character map')
    if any(g > 0xFF for _, g in charmap):
        sys.exit('character map points outside the 256-glyph font')
    extra = glyph_rows(img, LIT_EXTRA)
    CHARMAP_OUT.write_text(
        HEADER +
        '/* Stock text (FUN_4201a5c8): code points below 0x80 draw that font glyph;\n'
        ' * others are looked up in fw_vendor_charmap (FUN_4201bae8), then in\n'
        ' * fw_vendor_extra_glyphs (FUN_4201baac, rows top to bottom, bit 4 = left\n'
        ' * column); anything else draws \'?\'. Both tables are sorted by code point. */\n'
        '#include "vendor_charmap.h"\n\n'
        'const FwCharMapEntry fw_vendor_charmap[FW_VENDOR_CHARMAP_COUNT] = {\n%s\n};\n\n'
        'const FwRowGlyph fw_vendor_extra_glyphs[FW_VENDOR_EXTRA_COUNT] = {\n%s\n};\n'
        % ('\n'.join('    {0x%04X, 0x%02X},  /* %s */' % (c, g, chr(c)) for c, g in charmap),
           glyph_lines(extra)),
        encoding='utf-8', newline='\n')
    if len(extra) != 63:
        sys.exit('unexpected extra glyph count %d' % len(extra))

    date = glyph_rows(img, LIT_DATE_GLYPHS)
    if len(date) != 42:
        sys.exit('unexpected date glyph count %d' % len(date))
    base = img.u32(LIT_LOCALES)
    locales = []
    for i in range(LOCALES):
        words = [img.cstr(img.u32(base + 80 * i + 4 * j)) for j in range(20)]
        locales.append(words)
    if locales[0][0] != 'en' or locales[0][1] != 'SUN' or locales[0][8] != 'JAN':
        sys.exit('locale table does not start with English')
    zbase = img.u32(LIT_ZONE_NAMES)
    zones = []
    for i in range(ZONES):
        minutes, ptr = struct.unpack('<hxxI', img.read(zbase + 8 * i, 8))
        if not ptr:
            sys.exit('zone table entry without a name')
        zones.append((minutes, img.cstr(ptr)))
    loc_lines = []
    for w in locales:
        loc_lines.append('    {%s,\n     {%s},\n     {%s}},' % (
            c_string(w[0]), ', '.join(c_string(s) for s in w[1:8]), ', '.join(c_string(s) for s in w[8:20])))
    CLOCK_OUT.write_text(
        HEADER +
        '#include "clock_tables.h"\n\n'
        '/* FUN_4200f7ec draws these code points itself (8 rows, bit 4 = left column);\n'
        ' * every other character in a date goes through the normal text path. */\n'
        'const FwRowGlyph fw_clock_date_glyphs[FW_CLOCK_DATE_GLYPHS] = {\n%s\n};\n\n'
        '/* FUN_42007664: matched by code; unknown codes use the first (English). */\n'
        'const FwClockLocale fw_clock_locales[FW_CLOCK_LOCALES] = {\n%s\n};\n\n'
        '/* FUN_42019f90: first entry with a matching standard offset names the zone. */\n'
        'const FwZoneName fw_clock_zone_names[FW_CLOCK_ZONE_NAMES] = {\n%s\n};\n'
        % (glyph_lines(date), '\n'.join(loc_lines),
           '\n'.join('    {%d, %s},' % (m, c_string(n)) for m, n in zones)),
        encoding='utf-8', newline='\n')
    print('wrote %s (%d map entries, %d extra glyphs)' % (CHARMAP_OUT.name, len(charmap), len(extra)))
    print('wrote %s (%d date glyphs, %d locales, %d zone names)' % (CLOCK_OUT.name, len(date), len(locales), len(zones)))


if __name__ == '__main__':
    main()
