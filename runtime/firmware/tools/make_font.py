"""Generate components/fw_text/font5x7.c from Adafruit-GFX-Library glcdfont.c.

    py runtime/firmware/tools/make_font.py

Pinned source (BSD licence, notice preserved in the output). The table is
byte-identical to the font in the vendor firmware (0x3c0f736c in app
0ab195d6), so owned text renders exactly like the stock display.
"""
import re
import subprocess
import sys
from pathlib import Path

URL = 'https://github.com/adafruit/Adafruit-GFX-Library.git'
COMMIT = 'bc85af5aa4802cb85626c188cbc632343e3dae14'
HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / 'build' / 'deps' / 'adafruit-gfx'
OUT = HERE.parent / 'components' / 'fw_text' / 'font5x7.c'


def fetch():
    if not SRC.exists():
        subprocess.run(['git', 'clone', '-q', '--filter=blob:none', '--no-checkout', URL, str(SRC)], check=True)
        subprocess.run(['git', 'sparse-checkout', 'set', '--no-cone', 'glcdfont.c', 'license.txt'], cwd=SRC, check=True)
    subprocess.run(['git', 'fetch', '-q', 'origin', COMMIT], cwd=SRC, check=True)
    subprocess.run(['git', 'checkout', '-q', '--detach', COMMIT], cwd=SRC, check=True)
    head = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=SRC, capture_output=True, text=True).stdout.strip()
    if head != COMMIT:
        sys.exit('Adafruit-GFX checkout is not at the pinned commit')


def main():
    fetch()
    src = (SRC / 'glcdfont.c').read_text()
    body = src[src.index('{') + 1:src.rindex('}')]
    table = [int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]{2})', body)]
    if len(table) != 256 * 5:
        sys.exit('unexpected glcdfont size %d' % len(table))
    licence = (SRC / 'license.txt').read_text().strip()
    rows = []
    for c in range(256):
        g = table[c * 5:c * 5 + 5]
        rows.append('    ' + ', '.join('0x%02X' % b for b in g) + ',  /* 0x%02X */' % c)
    OUT.write_text(
        '/* GENERATED by tools/make_font.py - do not edit.\n'
        ' * Classic 5x7 font from Adafruit-GFX-Library glcdfont.c, commit %s.\n'
        ' * Five column bytes per glyph, bit 0 = top row; 256 glyphs in CP437 order.\n'
        ' *\n'
        ' * Original licence:\n *\n%s\n */\n'
        '#include "fw_text.h"\n\n'
        'const uint8_t fw_font5x7[256 * 5] = {\n%s\n};\n'
        % (COMMIT, '\n'.join(' * ' + line if line else ' *' for line in licence.splitlines()), '\n'.join(rows)),
        encoding='utf-8', newline='\n')
    print('wrote %s (%d glyphs)' % (OUT, 256))


if __name__ == '__main__':
    main()
